def describe(widget, key: str):
    """Применить tooltip из реестра к виджету. Возвращает виджет."""
    try:
        _title, _desc, tip = SETTING_DEFS.get(key, ("", "", ""))
        if tip:
            widget.setToolTip(tip)
    except Exception:
        pass
    return widget


def full_text(key: str) -> str:
    """Название + описание для диалогов/справки."""
    title, desc, _tip = SETTING_DEFS.get(key, (key, "", ""))
    return f"{title}\n{desc}".strip()
